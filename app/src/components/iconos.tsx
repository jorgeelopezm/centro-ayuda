/**
 * Icono de categoría por nombre. `null`/ausente («sin icono») o un nombre que este
 * despliegue no conoce no pintan nada: la categoría queda solo con su nombre, que es
 * lo que siempre comunica el significado (los iconos son `aria-hidden`).
 */
export function Icono({ nombre, ...props }: { nombre: NombreIcono | null | undefined } & PropsIcono) {
  const Componente = nombre ? porNombre[nombre] : undefined
  return Componente ? <Componente {...props} /> : null
}
